@pytest.mark.parametrize("optional_status", ["failed", "not_run"])
def test_optional_incomplete_check_warns_without_failing_revalidation(
    installed_case: RevalidationCase, optional_status: CheckStatus
) -> None:
    case = installed_case
    optional_id = "fluxos.optional-diagnostic"
    case.validator.statuses[optional_id] = optional_status
    before = case.registry.snapshot()

    outcome = installer.validate_models(case.config)

    assert outcome.success is True
    assert outcome.exit_code == 0
    assert len(outcome.groups) == 1
    group = outcome.groups[0]
    assert group.status == "revalidated"
    assert group.installation_id == case.record.installation_id
    assert group.error is None
    assert group.optional_checks_incomplete == (optional_id,)
    assert group.validation_status == optional_status
    assert group.model_dump(mode="json")["optional_checks_incomplete"] == [optional_id]
    snapshot = case.registry.snapshot()
    assert snapshot.generation == before.generation + 1
    assert snapshot.active == before.active and snapshot.health == before.health
    assert snapshot.validation_status[case.record.installation_id] == optional_status
    assert case.registry.resolve("fluxos", "docker").record == case.record
    assert len(case.validator.requests) == 1


@pytest.mark.parametrize(
    "mandatory_status,expected_health",
    [("failed", "verified"), ("not_run", "verified")],
)
def test_incomplete_mandatory_check_never_reports_revalidation_success(
    installed_case: RevalidationCase,
    mandatory_status: CheckStatus,
    expected_health: str,
) -> None:
    case = installed_case
    case.validator.statuses["fluxos.reference"] = mandatory_status
    before = case.registry.snapshot()

    outcome = installer.validate_models(case.config)

    assert outcome.success is False
    assert outcome.exit_code == 4
    assert len(outcome.groups) == 1
    group = outcome.groups[0]
    assert group.status == "failed"
    assert group.error is not None
    assert group.error.code == ErrorCode.VALIDATION_FAILED
    snapshot = case.registry.snapshot()
    assert snapshot.health[case.record.installation_id] == expected_health
    assert snapshot.active == before.active
    assert snapshot.generation == before.generation + 1
    assert snapshot.validation_status[case.record.installation_id] == mandatory_status
    selected = case.registry.resolve("fluxos", "docker")
    assert selected.record == case.record
    assert selected.validation_status == mandatory_status


def supersede_then_corrupt_history(case: RevalidationCase) -> InstallationRecord:
    """Retain a damaged historical record while its successor remains valid."""
    checks = tuple(
        CheckSpec.model_validate(value)
        for value in json.loads(case.record.suite_ref.path.read_bytes())
    )
    candidate = CandidateArtifact(
        attempt_id=uuid4(),
        group=case.record.group,
        artifact=case.record.artifact,
        build_spec_sha256=case.record.build_spec_sha256,
        toolchain_path=case.record.toolchain_ref.path,
        toolchain_sha256=case.record.toolchain_ref.sha256,
    )
    report = case.validator.validate(
        ValidationRequest(
            candidate=candidate,
            checks=checks,
            validation_dir=case.config.validation_root / str(candidate.attempt_id),
        )
    )
    replacement = case.registry.promote(candidate, report, case.registry.snapshot().generation)
    path = case.registry.root / "records" / f"{case.record.installation_id}.json"
    path.write_bytes(b"{}")
    case.validator.requests.clear()
    return replacement


@pytest.mark.parametrize("explicit_id", [True, False])
def test_cli_revalidates_selected_or_active_installation_despite_corrupt_history(
    installed_case: RevalidationCase, explicit_id: bool, capsys
) -> None:
    case = installed_case
    replacement = supersede_then_corrupt_history(case)
    args = ["models", "validate", "--data-root", str(case.config.data_root)]
    if explicit_id:
        args.extend(["--installation-id", str(replacement.installation_id)])

    assert main(args) == 0

    output = json.loads(capsys.readouterr().out)
    assert [group["installation_id"] for group in output["groups"]] == [
        str(replacement.installation_id)
    ]
    assert len(case.validator.requests) == 1
    assert case.registry.resolve("fluxos", "docker").record == replacement


def test_requested_corrupt_installation_remains_an_error(installed_case: RevalidationCase) -> None:
    case = installed_case
    replacement = supersede_then_corrupt_history(case)

    with pytest.raises(FloodcastError) as caught:
        installer.validate_models(case.config, installation_id=case.record.installation_id)

    assert caught.value.code == ErrorCode.REGISTRY_CORRUPT
    assert case.validator.requests == []
    assert case.registry.resolve("fluxos", "docker").record == replacement
