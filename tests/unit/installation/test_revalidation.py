CheckStatus = Literal["passed", "failed", "not_run"]


def write_evidence(path: Path, content: bytes) -> EvidenceRef:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(content)
    return EvidenceRef(path=path, sha256=sha256(content).hexdigest())


class ReportingValidator:
    """Produce typed observations while exercising the real registry persistence."""

    def __init__(self) -> None:
        self.statuses: dict[str, CheckStatus] = {}
        self.requests: list[ValidationRequest] = []

    def validate(self, request: ValidationRequest) -> ValidationReport:
        self.requests.append(request)
        results = []
        for check in request.checks:
            status = self.statuses.get(check.check_id, "passed")
            evidence = write_evidence(
                request.validation_dir / f"{check.check_id}.json",
                canonical_json_bytes({"check_id": check.check_id, "status": status}),
            )
            now = utc_now()
            results.append(
                CheckResult(
                    check_id=check.check_id,
                    status=status,
                    reason="Controlled observation from the validation test double",
                    evidence_refs=(evidence,),
                    started_at=None if status == "not_run" else now,
                    finished_at=None if status == "not_run" else now,
                    exit_code=None if status == "not_run" else int(status == "failed"),
                )
            )
        return ValidationReport(
            attempt_id=request.candidate.attempt_id,
            artifact_id=request.candidate.artifact.artifact_id,
            build_spec_sha256=request.candidate.build_spec_sha256,
            suite_sha256=check_suite_sha256(request.checks),
            results=tuple(results),
        )


@dataclass(frozen=True)
class RevalidationCase:
    config: RuntimeConfig
    registry: Registry
    record: InstallationRecord
    validator: ReportingValidator


